# ── 阶段性归纳：统计数据 → 复习与提升方案 ──────────────────────────────
# 约束理由（这是本模块最重要的一条）：
#   1) 统计数字**一律由 SQL 算好**再喂给模型，绝不让模型自己去数。
#      模型负责的是「解释趋势」和「安排优先级」，让它做算术是它最容易出错、
#      且我们无法察觉的用法。
#   2) 语气同样要盯住。这份方案孩子和家长都会看到，默认输出会写成
#      「鉴于该生近期表现」「建议加强专项训练」，读起来像通知书。
#      家长想要的其实是「这周该陪他练什么」，孩子想要的是别被说教。
#      因此要求：说人话、给能直接执行的动作、不评价孩子。
#   3) encouragement 是**最容易变成空话**的字段（「继续努力，你一定可以」）。
#      空话比没有更伤，孩子一眼就看穿。因此强制它必须引用数据里的具体事实。
